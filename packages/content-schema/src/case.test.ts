import { describe, expect, it } from "vitest";
import { caseSchema, worldRosterSchema } from "./case";

const validCase = {
  id: "tutorial-nulls",
  world: "boss-fights",
  tier: "tutorial",
  datasetPath: "/datasets/world-1/tutorial-nulls.csv",
  datasetLicense: {
    license: "CC0-1.0",
    provenance: "Synthetic, generated by a seeded script.",
  },
  strings: {
    title: "The Null Hydra",
    briefing: "Every missing value regenerates the boss. Clear them all.",
  },
  starterCode: {
    python: "df.isna().sum()",
    sql: "SELECT * FROM data WHERE email IS NULL;",
  },
  winCondition: {
    all: [{ predicate: "no_nulls", column: "email" }],
  },
};

describe("caseSchema", () => {
  it("accepts a valid case", () => {
    expect(caseSchema.safeParse(validCase).success).toBe(true);
  });

  it("accepts optional columnHints", () => {
    const result = caseSchema.safeParse({
      ...validCase,
      columnHints: { email: { widthPx: 180, numeric: false }, id: { numeric: true } },
    });
    expect(result.success).toBe(true);
  });

  it("rejects an id with invalid characters", () => {
    const result = caseSchema.safeParse({ ...validCase, id: "Tutorial Nulls!" });
    expect(result.success).toBe(false);
  });

  it("rejects a win condition with no predicates", () => {
    const result = caseSchema.safeParse({ ...validCase, winCondition: { all: [] } });
    expect(result.success).toBe(false);
  });

  it("rejects an unknown world", () => {
    const result = caseSchema.safeParse({ ...validCase, world: "the-underworld" });
    expect(result.success).toBe(false);
  });

  it("rejects a case missing datasetLicense", () => {
    const { datasetLicense: _unused, ...caseWithoutLicense } = validCase;
    const result = caseSchema.safeParse(caseWithoutLicense);
    expect(result.success).toBe(false);
  });

  it("rejects a case missing starterCode", () => {
    const { starterCode: _unused, ...caseWithoutStarter } = validCase;
    const result = caseSchema.safeParse(caseWithoutStarter);
    expect(result.success).toBe(false);
  });

  it("rejects a case with starterCode missing the sql variant", () => {
    const result = caseSchema.safeParse({
      ...validCase,
      starterCode: { python: "df.isna().sum()" },
    });
    expect(result.success).toBe(false);
  });

  it("rejects a case missing tier", () => {
    const { tier: _unused, ...caseWithoutTier } = validCase;
    const result = caseSchema.safeParse(caseWithoutTier);
    expect(result.success).toBe(false);
  });

  it("rejects an unknown tier", () => {
    const result = caseSchema.safeParse({ ...validCase, tier: "mini-boss" });
    expect(result.success).toBe(false);
  });

  it.each(["tutorial", "mid-boss", "final-boss"] as const)("accepts tier %s", (tier) => {
    const result = caseSchema.safeParse({ ...validCase, tier });
    expect(result.success).toBe(true);
  });

  it("accepts a stacked win condition combining multiple predicate kinds", () => {
    const result = caseSchema.safeParse({
      ...validCase,
      winCondition: {
        all: [
          { predicate: "no_nulls", column: "email" },
          { predicate: "no_whitespace", column: "email" },
          { predicate: "consistent_casing", column: "email", case: "lower" },
          { predicate: "valid_dtype", column: "signup_year", dtype: "int" },
          { predicate: "no_outliers", column: "age", min: 0, max: 120 },
          { predicate: "no_duplicates", columns: ["email"] },
        ],
      },
    });
    expect(result.success).toBe(true);
  });

  it("rejects a consistent_casing predicate with an invalid case value", () => {
    const result = caseSchema.safeParse({
      ...validCase,
      winCondition: {
        all: [{ predicate: "consistent_casing", column: "email", case: "sentence" }],
      },
    });
    expect(result.success).toBe(false);
  });

  it("rejects a valid_dtype predicate with an unknown dtype", () => {
    const result = caseSchema.safeParse({
      ...validCase,
      winCondition: {
        all: [{ predicate: "valid_dtype", column: "age", dtype: "complex128" }],
      },
    });
    expect(result.success).toBe(false);
  });
});

describe("worldRosterSchema", () => {
  it("accepts a valid roster", () => {
    const result = worldRosterSchema.safeParse({
      world: "boss-fights",
      caseIds: ["w1-01-nul-sentinel", "w1-02-double-take"],
    });
    expect(result.success).toBe(true);
  });

  it("rejects an empty caseIds list", () => {
    const result = worldRosterSchema.safeParse({ world: "boss-fights", caseIds: [] });
    expect(result.success).toBe(false);
  });

  it("rejects an unknown world", () => {
    const result = worldRosterSchema.safeParse({
      world: "the-underworld",
      caseIds: ["x"],
    });
    expect(result.success).toBe(false);
  });
});
