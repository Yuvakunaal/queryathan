  const lastDay = utc(2026, 7, 31);
  const activity = [];
  for (const user of users) {
    const signup = Date.parse(user.signup_date + "T00:00:00Z");
    const engaged = chance(0.55);
    const events = engaged ? int(2, 7) : int(0, 2);
    for (let k = 0; k < events; k += 1) {
      const ms = signup + int(0, 75) * DAY;
      if (ms <= lastDay)
        activity.push({ user_id: user.user_id, active_date: dateStr(ms) });
    }
  }
  writeCsv("users.csv", ["user_id", "signup_date"], shuffle(users));
  writeCsv("activity.csv", ["user_id", "active_date"], shuffle(activity));

  const cohorts = new Map();
  for (const user of users) {
    const key = user.signup_date.slice(0, 7);
    cohorts.set(key, [...(cohorts.get(key) ?? []), user.user_id]);
  }
  const nextMonth = (key) => {
    const [y, m] = key.split("-").map(Number);
    return m === 12 ? `${y + 1}-01` : `${y}-${pad(m + 1)}`;
  };
