const csvCell = (v) => {
  const s = String(v);
  return /[",\n]/.test(s) || /^\s|\s$/.test(s) ? `"${s.replaceAll('"', '""')}"` : s;
};
const toCsv = (cols, rows) =>
  [cols.join(","), ...rows.map((r) => cols.map((c) => csvCell(r[c])).join(","))].join(
    "\n",
  ) + "\n";
const writeCsv = (name, cols, rows) =>
  writeFileSync(join(dataDir, name), toCsv(cols, rows));

/** Date helpers on plain numbers, so nothing depends on the machine's time zone. */
const DAY = 86_400_000;
const utc = (y, m, d, hh = 0, mm = 0, ss = 0) => Date.UTC(y, m - 1, d, hh, mm, ss);
const dateStr = (ms) => {
  const d = new Date(ms);
  return `${d.getUTCFullYear()}-${pad(d.getUTCMonth() + 1)}-${pad(d.getUTCDate())}`;
};
const stampStr = (ms) => {
  const d = new Date(ms);
  return `${dateStr(ms)} ${pad(d.getUTCHours())}:${pad(d.getUTCMinutes())}:${pad(d.getUTCSeconds())}`;
};

