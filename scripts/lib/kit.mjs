/** Everything one world needs: seeded random helpers, data and case writers, roster. */
export function createWorld({ number, id, dir, seed, script, label }) {
  const random = mulberry32(seed);
  const dataDir = join(root, `apps/web/public/datasets/world-${number}`);
  const casesDir = join(root, `content/cases/${id}`);
  mkdirSync(dataDir, { recursive: true });
  mkdirSync(casesDir, { recursive: true });
  const license = {
    license: "CC0-1.0",
    provenance: `Synthetic — generated by scripts/${script} with a seeded deterministic PRNG. All names, ids, dates and amounts are invented.`,
  };
  const caseIds = [];
  const files = [];
  const kit = {
    random,
    pick: (list) => list[Math.floor(random() * list.length)],
    int: (lo, hi) => lo + Math.floor(random() * (hi - lo + 1)),
    chance: (p) => random() < p,
    shuffle(list) {
      const out = [...list];
      for (let i = out.length - 1; i > 0; i -= 1) {
        const j = Math.floor(random() * (i + 1));
        [out[i], out[j]] = [out[j], out[i]];
      }
      return out;
    },
    license,
    writeCsv(name, cols, rows, note) {
      writeFileSync(join(dataDir, name), toCsv(cols, rows));
      files.push(`- \`${name}\`: ${rows.length} rows, \`${cols.join(", ")}\`${note ? `; ${note}` : ""}.`);
      return `/datasets/world-${number}/${name}`;
    },
    writeCase(caseId, body) {
      caseIds.push(caseId);
      writeFileSync(
        join(casesDir, `${caseId}.json`),
        JSON.stringify({ id: caseId, world: id, ...body }, null, 2) + "\n",
      );
    },
    finish() {
      writeFileSync(
        join(root, `content/rosters/${id}.json`),
        JSON.stringify({ world: id, caseIds }, null, 2) + "\n",
      );
      writeFileSync(
        join(dataDir, "LICENSES.md"),
        `# World ${number} dataset licenses\n\nAll files are **CC0** (public domain dedication), synthetic, and generated by\n[\`scripts/${script}\`](../../../../scripts/${script}) with a seeded deterministic PRNG. Names,\nids, dates and amounts are invented. Regenerate with \`node scripts/${script}\`; the same script\nwrites the case files and their expected answers, so data and answer key cannot drift apart.\n\n${files.join("\n")}\n`,
      );
      console.log(`${label} written: ${caseIds.length} cases.`);
    },
  };
  return kit;
}
