// Shared helpers for the world generators (Worlds 7 to 9): a seeded PRNG, CSV writing,
// date arithmetic on plain numbers (no time zone surprises), and the case-file writer.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const root = join(dirname(fileURLToPath(import.meta.url)), "../..");

export function mulberry32(seed) {
  let a = seed;
  return function random() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export const round = (n, places) => {
  const f = 10 ** places;
  return Math.round((n + Number.EPSILON) * f) / f;
};
export const pad = (n) => String(n).padStart(2, "0");

export const DAY = 86_400_000;
export const utc = (y, m, d, hh = 0, mm = 0, ss = 0) => Date.UTC(y, m - 1, d, hh, mm, ss);
export const dateStr = (ms) => {
  const d = new Date(ms);
  return `${d.getUTCFullYear()}-${pad(d.getUTCMonth() + 1)}-${pad(d.getUTCDate())}`;
};
export const stampStr = (ms) => {
  const d = new Date(ms);
  return `${dateStr(ms)} ${pad(d.getUTCHours())}:${pad(d.getUTCMinutes())}:${pad(d.getUTCSeconds())}`;
};

const csvCell = (v) => {
  const s = v === null || v === undefined ? "" : String(v);
  return /[",\n]/.test(s) || /^\s|\s$/.test(s) ? `"${s.replaceAll('"', '""')}"` : s;
};
export const toCsv = (cols, rows) =>
  [cols.join(","), ...rows.map((r) => cols.map((c) => csvCell(r[c])).join(","))].join("\n") +
  "\n";

export const hint = (columns) =>
  Object.fromEntries(
    Object.entries(columns).map(([name, [widthPx, numeric]]) => [
      name,
      { widthPx, numeric },
    ]),
  );

