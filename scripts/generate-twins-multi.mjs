  const byProduct = new Map(products.map((p) => [p.product_id, p]));
  const rows = orders.map((o) => {
    const c = byCustomer.get(o.customer_id);
    const p = byProduct.get(o.product_id);
    return [
      o.order_id,
      c ? c.customer_name : null,
      c ? c.city : null,
      p.product_name,
      o.qty,
      round2((o.qty * p.cents) / 100),
    ];
  });

