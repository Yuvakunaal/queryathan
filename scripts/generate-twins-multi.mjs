          qty: [70, true],
          discount_pct: [120, true],
          customer_name: [150, false],
          segment: [100, false],
          product_name: [150, false],
          category: [110, false],
          unit_price: [100, true],
          store_name: [120, false],
          region: [90, false],
          line_total: [110, true],
