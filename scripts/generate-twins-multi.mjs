// Deterministic (seeded PRNG), everything invented. Run: node scripts/generate-twins-multi.mjs

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

function mulberry32(seed) {
  let a = seed;
  return function random() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const random = mulberry32(0x54574d4c); // "TWML"
const pick = (list) => list[Math.floor(random() * list.length)];
const int = (lo, hi) => lo + Math.floor(random() * (hi - lo + 1));
const round2 = (n) => Math.round((n + Number.EPSILON) * 100) / 100;

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dataDir = join(root, "apps/web/public/datasets/world-3");
const casesDir = join(root, "content/cases/the-twins");
